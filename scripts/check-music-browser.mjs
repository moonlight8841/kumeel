import assert from 'node:assert/strict'
import {createRequire} from 'node:module'
import {join} from 'node:path'
import {tmpdir} from 'node:os'
// Optional browser check; playwright-core installed separately outside the repository.
const require=createRequire(import.meta.url)
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||join(tmpdir(),'kumeel-browser-check/node_modules/playwright-core'))
const browser=await chromium.launch({executablePath:process.env.BROWSER_EXE||'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true})
try{
 const page=await browser.newPage({viewport:{width:1280,height:900}})
 const errors=[];let providerLoads=0
 page.on('pageerror',e=>errors.push(e.message))
 // Verify lifecycle without downloading or playing the external video.
 await page.route('https://www.youtube-nocookie.com/embed/**',route=>{providerLoads++;return route.fulfill({contentType:'text/html',body:'<p>Provider placeholder for lifecycle test</p>'})})
 await page.goto('http://127.0.0.1:4173/music',{waitUntil:'networkidle'})
 assert.equal(providerLoads,0)
 await page.locator('.music-library-filters button').nth(2).click()
 assert.equal(await page.locator('.music-library-card').count(),0)
 await page.locator('.music-library-filters button').first().click()
 await page.locator('.music-library-search input').fill('no-such-selection')
 assert.equal(await page.locator('.music-library-card').count(),0)
 await page.locator('.music-library-search input').fill('')
 assert.ok(await page.locator('.music-library-card').count()>0)
 await page.screenshot({path:join(tmpdir(),'kumeel-music-desktop.png'),fullPage:true})
 await page.locator('.music-dock-toggle').click()
 await page.locator('.music-dock iframe').waitFor()
 await page.waitForFunction(()=>document.querySelector('.music-dock iframe')?.contentWindow)
 const player=await page.locator('.music-dock iframe').elementHandle()
 await page.evaluate(()=>{window.__musicTestDocument=document;document.querySelector('.music-dock iframe').dataset.testIdentity='same-player'})
 await page.locator('header a[href="/writings"]').first().click()
 await page.waitForURL('**/writings')
 await page.waitForFunction(()=>document.querySelector('.writings-index'))
 assert.ok(await page.evaluate(()=>window.__musicTestDocument===document),'Navigation preserves document')
 assert.equal(await player.getAttribute('data-test-identity'),'same-player')
 assert.equal(await page.locator('.music-dock iframe').getAttribute('data-test-identity'),'same-player')
 assert.equal(providerLoads,1)
 await page.goBack()
 await page.waitForURL('http://127.0.0.1:4173/music')
 await page.waitForSelector('.music-library')
 assert.equal(providerLoads,1)
 await page.locator('a[href="/en/music"]').first().click()
 await page.waitForURL('**/en/music')
 await page.waitForFunction(()=>document.documentElement.lang==='en')
 assert.equal(await page.locator('.music-dock iframe').getAttribute('data-test-identity'),'same-player')
 await page.locator('.music-dock-minimize').click()
 assert.equal(await page.locator('.music-dock iframe').getAttribute('data-test-identity'),'same-player','Minimizing keeps the same player')
 const dock=await page.locator('.music-dock').boundingBox()
 assert.ok(dock.height<=140,`Minimized dock stays compact (${dock.height}px)`)
 await page.screenshot({path:join(tmpdir(),'kumeel-music-minimized.png')})
 await page.locator('.music-dock-minimize').click()
 assert.equal(await page.locator('.music-dock iframe').getAttribute('data-test-identity'),'same-player')
 await page.setViewportSize({width:390,height:844})
 const box=await page.locator('.music-dock iframe').boundingBox()
 assert.ok(box.width>=200&&box.height>=200&&box.x>=0&&box.x+box.width<=390)
 await page.locator('.music-dock-toggle').click()
 assert.equal(await page.locator('.music-dock iframe').count(),0)
 assert.deepEqual(errors,[])
 await page.screenshot({path:join(tmpdir(),'kumeel-music-mobile.png'),fullPage:true})
 console.log('Browser: on-demand load, unchanged iframe across writings/back/English navigation, mobile dimensions, close/unmount and no runtime errors passed. External video playback was mocked.')
}finally{await browser.close()}
